"""
Evaluation framework for WildlifeAI cognitive system.

This module provides tools to validate and quantify the performance of
pattern detection, insight generation, and anomaly detection.
"""
from typing import Dict, List, Any, Optional, Tuple
from datetime import datetime
import json
from pathlib import Path
from collections import defaultdict
import logging

logger = logging.getLogger(__name__)


class PatternEvaluator:
    """
    Evaluate ecological pattern detection accuracy.
    
    Validates system-generated insights against ground truth or
    synthetic test cases with known patterns.
    """
    
    def __init__(self):
        self.results = []
    
    def evaluate_temporal_patterns(
        self,
        detected_patterns: List[Dict],
        ground_truth: List[Dict]
    ) -> Dict[str, float]:
        """
        Evaluate temporal pattern detection (nocturnal/diurnal).
        
        Args:
            detected_patterns: Patterns detected by Insight Agent
            ground_truth: Known correct patterns
        
        Returns:
            Metrics dict with precision, recall, F1
        """
        # Match detections to ground truth
        true_positives = 0
        false_positives = 0
        false_negatives = 0
        
        gt_species = {p['species']: p['pattern'] for p in ground_truth}
        detected_species = {p['species']: p['pattern'] for p in detected_patterns}
        
        # Calculate metrics
        for species, true_pattern in gt_species.items():
            if species in detected_species:
                if detected_species[species] == true_pattern:
                    true_positives += 1
                else:
                    false_positives += 1
            else:
                false_negatives += 1
        
        # Additional false positives (detected but not in ground truth)
        for species in detected_species:
            if species not in gt_species:
                false_positives += 1
        
        precision = true_positives / (true_positives + false_positives) if (true_positives + false_positives) > 0 else 0
        recall = true_positives / (true_positives + false_negatives) if (true_positives + false_negatives) > 0 else 0
        f1 = 2 * (precision * recall) / (precision + recall) if (precision + recall) > 0 else 0
        
        return {
            'precision': precision,
            'recall': recall,
            'f1_score': f1,
            'true_positives': true_positives,
            'false_positives': false_positives,
            'false_negatives': false_negatives
        }
    
    def evaluate_anomaly_detection(
        self,
        detected_anomalies: List[Dict],
        true_anomalies: List[Dict],
        tolerance_hours: int = 24
    ) -> Dict[str, float]:
        """
        Evaluate anomaly detection accuracy.
        
        Args:
            detected_anomalies: Alerts generated by system
            true_anomalies: Known anomalies
            tolerance_hours: Time window for matching
        
        Returns:
            Metrics dict with precision, recall, F1
        """
        true_positives = 0
        matched_true = set()
        
        # Match detected to true anomalies
        for detected in detected_anomalies:
            for i, true in enumerate(true_anomalies):
                if i in matched_true:
                    continue
                
                # Match on species and approximate time
                if detected.get('species') == true.get('species'):
                    true_positives += 1
                    matched_true.add(i)
                    break
        
        false_positives = len(detected_anomalies) - true_positives
        false_negatives = len(true_anomalies) - len(matched_true)
        
        precision = true_positives / len(detected_anomalies) if detected_anomalies else 0
        recall = true_positives / len(true_anomalies) if true_anomalies else 0
        f1 = 2 * (precision * recall) / (precision + recall) if (precision + recall) > 0 else 0
        
        return {
            'precision': precision,
            'recall': recall,
            'f1_score': f1,
            'true_positives': true_positives,
            'false_positives': false_positives,
            'false_negatives': false_negatives
        }
    
    def evaluate_insight_quality(
        self,
        insights: List[Dict],
        min_confidence: float = 0.7
    ) -> Dict[str, Any]:
        """
        Evaluate overall insight generation quality.
        
        Metrics:
        - Insight diversity (types generated)
        - Average confidence
        - Coverage (species analyzed)
        """
        if not insights:
            return {
                'total_insights': 0,
                'unique_types': 0,
                'avg_confidence': 0,
                'species_coverage': 0
            }
        
        insight_types = set(i.get('type') for i in insights)
        species_analyzed = set(i.get('species') for i in insights if 'species' in i)
        
        # Calculate average confidence where available
        confidences = [i.get('confidence', 1.0) for i in insights if 'confidence' in i]
        avg_confidence = sum(confidences) / len(confidences) if confidences else 0
        
        return {
            'total_insights': len(insights),
            'unique_types': len(insight_types),
            'insight_types': list(insight_types),
            'avg_confidence': avg_confidence,
            'species_coverage': len(species_analyzed),
            'high_confidence_insights': sum(1 for c in confidences if c >= min_confidence)
        }
    
    def compare_pipelines(
        self,
        baseline_results: Dict,
        experimental_results: Dict
    ) -> Dict[str, Any]:
        """
        Compare two pipeline configurations.
        
        Args:
            baseline_results: Results from baseline pipeline
            experimental_results: Results from experimental pipeline
        
        Returns:
            Comparison metrics
        """
        comparison = {
            'baseline': baseline_results,
            'experimental': experimental_results,
            'improvements': {}
        }
        
        # Calculate improvements
        for metric in baseline_results:
            if isinstance(baseline_results[metric], (int, float)):
                if baseline_results[metric] > 0:
                    improvement = (
                        (experimental_results[metric] - baseline_results[metric]) 
                        / baseline_results[metric]
                    ) * 100
                    comparison['improvements'][metric] = f"{improvement:+.1f}%"
        
        return comparison
    
    def generate_report(
        self,
        evaluation_results: Dict,
        output_path: Optional[str] = None
    ) -> str:
        """
        Generate evaluation report.
        
        Args:
            evaluation_results: Dict of evaluation metrics
            output_path: Optional path to save report
        
        Returns:
            Report string
        """
        report_lines = [
            "=" * 80,
            "WildlifeAI Evaluation Report",
            f"Generated: {datetime.now().isoformat()}",
            "=" * 80,
            ""
        ]
        
        for section, metrics in evaluation_results.items():
            report_lines.append(f"\n{section.upper().replace('_', ' ')}")
            report_lines.append("-" * 80)
            
            if isinstance(metrics, dict):
                for key, value in metrics.items():
                    if isinstance(value, float):
                        report_lines.append(f"  {key}: {value:.3f}")
                    else:
                        report_lines.append(f"  {key}: {value}")
            else:
                report_lines.append(f"  {metrics}")
        
        report_lines.append("\n" + "=" * 80)
        
        report = "\n".join(report_lines)
        
        if output_path:
            Path(output_path).write_text(report)
            logger.info(f"Report saved to {output_path}")
        
        return report


class SyntheticValidator:
    """
    Generate synthetic test cases with known patterns for validation.
    
    This allows testing the system without requiring real labeled datasets.
    """
    
    def generate_temporal_test_case(
        self,
        species: str,
        pattern: str,  # 'nocturnal' or 'diurnal'
        num_observations: int = 20
    ) -> List[Dict]:
        """
        Generate synthetic observations with known temporal pattern.
        """
        from datetime import datetime, timedelta
        import random
        
        observations = []
        base_time = datetime.now() - timedelta(days=7)
        
        for i in range(num_observations):
            # Generate timestamp according to pattern
            if pattern == 'nocturnal':
                # Night hours: 20:00 - 04:00
                hour = random.choice(list(range(20, 24)) + list(range(0, 5)))
            else:  # diurnal
                # Day hours: 06:00 - 18:00
                hour = random.randint(6, 18)
            
            timestamp = base_time + timedelta(days=i, hours=hour, minutes=random.randint(0, 59))
            
            observations.append({
                'species': species,
                'confidence': random.uniform(0.7, 0.95),
                'timestamp': timestamp,
                'camera_id': f'CAM_{random.randint(1, 5):03d}',
                'image_path': f'synthetic_{species}_{i}.jpg'
            })
        
        return observations
    
    def generate_anomaly_test_case(
        self,
        species: str,
        baseline_rate: int = 2,  # observations per day
        spike_rate: int = 8,     # observations during anomaly
        anomaly_day: int = 5
    ) -> Tuple[List[Dict], Dict]:
        """
        Generate observations with activity spike anomaly.
        
        Returns:
            (observations, ground_truth_anomaly)
        """
        from datetime import datetime, timedelta
        import random
        
        observations = []
        base_time = datetime.now() - timedelta(days=10)
        
        for day in range(10):
            # Determine observation count for this day
            if day == anomaly_day:
                count = spike_rate
            else:
                count = baseline_rate
            
            for _ in range(count):
                timestamp = base_time + timedelta(
                    days=day,
                    hours=random.randint(0, 23),
                    minutes=random.randint(0, 59)
                )
                
                observations.append({
                    'species': species,
                    'confidence': random.uniform(0.7, 0.95),
                    'timestamp': timestamp,
                    'camera_id': f'CAM_001',
                    'image_path': f'synthetic_{species}_day{day}.jpg'
                })
        
        ground_truth = {
            'species': species,
            'type': 'activity_spike',
            'anomaly_day': anomaly_day,
            'expected_ratio': spike_rate / baseline_rate
        }
        
        return observations, ground_truth


def run_validation_suite() -> Dict[str, Any]:
    """
    Run complete validation suite with synthetic test cases.
    
    Returns:
        Complete validation results
    """
    evaluator = PatternEvaluator()
    validator = SyntheticValidator()
    
    results = {}
    
    # Test 1: Temporal pattern detection
    logger.info("Testing temporal pattern detection...")
    
    # Generate test cases
    nocturnal_obs = validator.generate_temporal_test_case('tiger', 'nocturnal', 20)
    diurnal_obs = validator.generate_temporal_test_case('deer', 'diurnal', 20)
    
    # Simulate detected patterns (would come from Insight Agent in real use)
    detected_patterns = [
        {'species': 'tiger', 'pattern': 'nocturnal'},
        {'species': 'deer', 'pattern': 'diurnal'}
    ]
    
    ground_truth_patterns = [
        {'species': 'tiger', 'pattern': 'nocturnal'},
        {'species': 'deer', 'pattern': 'diurnal'}
    ]
    
    temporal_metrics = evaluator.evaluate_temporal_patterns(
        detected_patterns,
        ground_truth_patterns
    )
    results['temporal_pattern_detection'] = temporal_metrics
    
    # Test 2: Anomaly detection
    logger.info("Testing anomaly detection...")
    
    anomaly_obs, ground_truth_anomaly = validator.generate_anomaly_test_case('elephant')
    
    # Simulate detected anomaly
    detected_anomalies = [{'species': 'elephant', 'type': 'activity_spike'}]
    true_anomalies = [ground_truth_anomaly]
    
    anomaly_metrics = evaluator.evaluate_anomaly_detection(
        detected_anomalies,
        true_anomalies
    )
    results['anomaly_detection'] = anomaly_metrics
    
    return results
